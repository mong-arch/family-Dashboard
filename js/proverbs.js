export function proverbOf(d = new Date()) {
  const start = new Date(d.getFullYear(), 0, 0);
  const day = Math.floor((d - start) / 86400000);
  const [text, meaning] = PROVERBS[day % PROVERBS.length];
  return { text, meaning };
}
